def _import_closure(entry: str = CODE_ENTRY) -> set:
    """The files under CODE_GLOBS that `entry` can import: its static import closure over those files (hygiene, decision log). Every import statement counts, a function's lazy one included, and so does
    `importlib.import_module` of a literal name (the compile backends); importing a module imports its packages'
    __init__ files. Imports of anything outside the globs (the standard library, numpy, networkx...) are not
    followed."""
    import ast
    mods = {}                                                         # module name -> file
    for g, root in zip(CODE_GLOBS, CODE_ROOTS):
        for f in glob.glob(g):
            parts = os.path.relpath(f, root)[:-3].split(os.sep)
            mods[".".join(parts[:-1] if parts[-1] == "__init__" else parts)] = f
    seen, todo = set(), [entry]
    while todo:
        m = todo.pop()
        if m in seen or m not in mods:
            continue
        seen.add(m)
        f = mods[m]
        pkg = m if f.endswith("__init__.py") else m.rpartition(".")[0]
        names = [pkg[:i] for i in range(len(pkg)) if pkg[i] == "."] + ([pkg] if pkg else [])   # (its packages' __init__)
        for node in ast.walk(ast.parse(open(f).read(), f)):
            if isinstance(node, ast.Import):
                for a in node.names:
                    p = a.name.split(".")
                    names += [".".join(p[:i]) for i in range(1, len(p) + 1)]
            elif isinstance(node, ast.ImportFrom):
                base = node.module or ""
                if node.level:
                    up = pkg.split(".")[:len(pkg.split(".")) - node.level + 1] if pkg else []
                    base = ".".join(up + ([node.module] if node.module else []))
                p = base.split(".")
                names += [".".join(p[:i]) for i in range(1, len(p) + 1)] + [base + "." + a.name for a in node.names]
            elif (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "import_module"
                  and node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)):
                names.append(node.args[0].value)
        todo.extend(n for n in names if n in mods and n not in seen)
    return {mods[m] for m in seen}


def _code_paths() -> list:
    """The executing source files, repo-relative, sorted: the files under CODE_GLOBS the simulator imports
    (`_import_closure`).  This list IS the required code inventory (versioned by CODE_INVENTORY_VERSION): a result's
    fingerprint must carry exactly these paths with hex hashes, so removing / adding an inventoried file is detected
    structurally, not only by digest (round-3 A3/B3)."""
    return sorted(os.path.relpath(f, ROOT) for f in _import_closure())


def _code_hashes() -> dict:
    """sha256 of every inventoried source file (`_code_paths`: the files under CODE_GLOBS -- froq/*.py,
    froq/semantics/*.py, hw/golden/*.py and third_party/swiper/swiper/*.py --
    that the simulator imports), one entry per file (repo-relative keys).  Per-file entries, never an aggregate:
    removing or changing any inventoried file changes the mapping, which sweep.py's resume comparison and
    load_profile's provenance check detect."""
    return {p: _sha(os.path.join(ROOT, p)) for p in _code_paths()}


def _program_qubit_count(events_path: str) -> int:
    """The number of program qubits of a schedule -- the wires with role "program" in the events document (exactly
    EventStream.program_wires for the campaign schedules; run_one asserts that against the loaded stream). The wires
    table precedes the giant events array in the file, so the scan reads the file in 4 MiB chunks only until the table
    closes -- never a full parse. (it read the first 4 MiB only, and the 20-qubit programs' tables end
    near 30 MB.)"""
    CHUNK = 1 << 22
    with open(events_path, "rb") as f:
        buf = f.read(CHUNK)
        i = buf.find(b'"wires"')
        while i < 0:                                            # (the key itself past the first chunk)
            more = f.read(CHUNK)
            if not more:
                raise ValueError("%s: no wires table (schema changed?)" % events_path)
            keep = len(buf) - 8
            buf = buf[keep:] + more
            i = buf.find(b'"wires"')
        j = buf.find(b"{", i)
        while j < 0:
            more = f.read(CHUNK)
            if not more:
                raise ValueError("%s: malformed wires table" % events_path)
            buf += more
            j = buf.find(b"{", i)
        table, depth, in_str, esc, k = bytearray(), 0, False, False, j
        while True:                                             # balanced-brace scan, string-literal aware, chunk by chunk
            while k < len(buf):
                c = buf[k]
                if in_str:
                    if esc:
                        esc = False
                    elif c == 0x5C:                             # backslash
                        esc = True
                    elif c == 0x22:                             # double quote
                        in_str = False
                elif c == 0x22:
                    in_str = True
                elif c == 0x7B:                                 # {
                    depth += 1
                elif c == 0x7D:                                 # }
                    depth -= 1
                    if depth == 0:
                        table += buf[j:k + 1]
                        return sum(1 for t in json.loads(table.decode()).values() if t.get("role") == "program")
                k += 1
            table += buf[j:]
            buf, j, k = f.read(CHUNK), 0, 0
            if not buf:
                raise ValueError("%s: the wires table does not end before the end of the file" % events_path)


def _manifest_fork_commit(manifest_path: str):
    """The compiler fork commit recorded in the converter's manifest (None when no manifest exists)."""
    if not os.path.exists(manifest_path):
        return None
    try:
        return (json.load(open(manifest_path)).get("compiler") or {}).get("fork_commit")
    except Exception:
        return None


def shared_inputs(bench: str, sched: str, sem: Semantics, lat: LatencyTable) -> dict:
    """Everything a run of this (program, d, table) consumes: the schedule, the events, the converter manifest and its
    compiler fork commit, the C1/C2/C3 certificates, the semantics rules, the per-file hashes of the executing code
    together with the versioned inventory of those files, the recovery snippet cache actually consulted (schema, file
    sha and the builder slicer sha recorded in it -- round-3 A2/B1(c): a run with a different or missing cache cannot
    share a fingerprint with a normal one) and the latency table.  The fingerprint's shared part is this plus the
    path delay; a training profile records exactly this dict (training always runs at path 0) and `load_profile`
    refuses a profile whose copy differs."""
    p = schedule_paths(bench, sched)
    code = _code_hashes()
    extra = {} if _contract.RECOVERY_MODE == "cancel" else dict(recovery_mode=_contract.RECOVERY_MODE)   # absent = Froq's cancellation (undo_redo)
    if _contract.CONTRACT_MODE != "full":                                 # Q-nomeas: absent = the measurement-aware walk
        extra["contract_mode"] = _contract.CONTRACT_MODE
    if sem.tables.library != "shortened":                                # Q-v5scripts (the C3 hash below differs too)
        extra["recovery_library"] = sem.tables.library
    if _contract.ur_own():                                               # UR at its own reach; absent = comp
        extra["ur_reach"] = "own"
    return dict(**extra, lss=_sha(p["lss"]), events=_sha(p["events"]),
                manifest=(_sha(p["manifest"]) if os.path.exists(p["manifest"]) else None),
                compiler_fork_commit=_manifest_fork_commit(p["manifest"]),
                tables={k: _sha(v) for k, v in sem.tables.paths.items()}, rules_version=RULES_VERSION,
                compile_backend=sem.compile_backend, code=code,
                code_inventory=dict(version=CODE_INVENTORY_VERSION, files=sorted(code)),
                snippet_cache=(snippet_cache_identity(_program_qubit_count(p["events"])) if sem.compile_backend == "real" else None),
                latency_table=dict(kind=lat.kind, sha=_sha(lat.path)),
                predictor=dict(q_value=0.9, client_latency=1))


def sensitivity_settings(decode_scale: float = 1.0, workspace_cap: int | None = None, t_supply: dict | None = None,
                         full_decode_scale: float = 1.0, hw_limits: str | None = None, decoder_salt: int | None = None,
                         hw_limits_file: str | None = None) -> dict:
    """The knobs that are on (gap analysis rule 25), and rule 57's full-decoder speed, canonical; {} when every
    knob is off. Unit settings: every arm of a cell takes the same, and each is in the shared fingerprint, the file names
    and the training profile's source."""
    assert hw_limits or not hw_limits_file, "--hw-limits-file is read by the hardware-limit mode (--hw-limits)"
    out = {}
    if float(decode_scale) != 1.0:
        out["decode_scale"] = float(decode_scale)
    if float(full_decode_scale) != 1.0:
        out["full_decode_scale"] = float(full_decode_scale)
    if workspace_cap:
        out["workspace_cap"] = int(workspace_cap)
    if t_supply:
        out["t_supply"] = dict(period=str(Fraction(str(t_supply["period"]))), buffer=int(t_supply.get("buffer", 1)),
                               start=str(t_supply.get("start", "full")))
    if hw_limits:                                                     # round 5, rule 66: the hardware-limit mode (froq/hwlimits.py)
        from . import hwlimits as _hwl
        assert hw_limits in _hwl.SETTINGS, hw_limits
        out["hw_limits"] = dict(setting=str(hw_limits), sha256=_hwl.load(hw_limits_file)[1])   # (round 6, F(iii): --hw-limits-file's)
    if decoder_salt is not None:                                      # a replicate's own decoder streams (froq/latency.py)
        assert int(decoder_salt) >= 1, ("--decoder-salt is an integer >= 1", decoder_salt)
        out["decoder_salt"] = int(decoder_salt)
    return out


