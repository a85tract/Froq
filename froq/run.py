    if w2_co: tag += "_wo%s" % _sha(w2_co)[:8]                       # (plan v2 2.2): the decision's overhead price, its file by its hash
    if w2_margin and w2_margin != "0": tag += "_wm%s" % w2_margin    # (2.3): the decision's margin, d or 4d rounds
    if w2_sd: tag += "_sd%s" % _sha(w2_sd)[:8]                       # (start-delay note v2 2.2): the correction's file by its hash
    tag += UR_TAGS.get(recovery, "")                                 # the routed undo-fixup-redo recovery; its variants
