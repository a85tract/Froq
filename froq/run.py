CHECKPOINT_FORMAT = "scoutq-e2e-checkpoint/2"   # /2: a header first (format, interpreter), then the state, then a
                                               # trailer (the sets recorded with their layouts, and those pickled by value)
STOPPED = 3                                                           # exit code of a part that stopped at its limit (resume with the same command)


class _EmptyCell:
    """Marks an unbound closure cell in a checkpoint."""


def _function_shell(code: bytes, module: str, name: str, ncells: int):
    """A nested function rebuilt from its marshalled code with empty cells (filled by `_function_fill` once memoised)."""
    return types.FunctionType(marshal.loads(code), sys.modules[module].__dict__, name, None, tuple(types.CellType() for _ in range(ncells)))


def _function_fill(fn, state) -> None:
    cells, defaults, kwdefaults, qualname, attrs = state
    for cell, v in zip(fn.__closure__ or (), cells):
        if v is not _EmptyCell:
            cell.cell_contents = v
    fn.__defaults__, fn.__kwdefaults__, fn.__qualname__ = defaults, kwdefaults, qualname
    fn.__dict__.update(attrs)


class _CheckpointPickler(pickle.Pickler):
    """pickle, plus the run's nested functions by value -- the latency sampler closure and the device's keyed decoder
    draw (`LatencyTable.sampler`, `ScoutDeviceManager._install_keyed_decoder`), which plain pickle refuses. Their code
    goes through marshal: only the same interpreter and the same code may resume, and the resume checks the code hashes.
    The cells are filled after the function is memoised, so a cycle through a closure (the draw's cells hold the device
    and the decoder that hold the draw) resolves. every set of hash-stable elements keeps its hash table's layout
    (`froq.setlayout`), so a resumed run iterates its sets as the whole run does. The C pickler saves exact sets and
    frozensets before it consults `reducer_override`, so those go out as persistent ids (`_CheckpointUnpickler`
    rebuilds them; a set met again is a reference to the first, so sharing survives); set subclasses, which may carry
    attributes that lead back to them, go through `reducer_override` and pickle's own memo."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._set_ids, self._set_keep, self._by_value = {}, [], {}

    def persistent_id(self, obj):
        t = type(obj)
        if t is not set and t is not frozenset:
            return None
        k = self._set_ids.get(id(obj))
        if k is not None:
            return ("set_ref", k)
        r = setlayout.reduce(obj)
        if r is None:                                                    # an element hashes differently in another
            self._by_value[id(obj)] = obj                                # process: its order cannot matter (counted)
            return None
        k = len(self._set_keep)
        self._set_ids[id(obj)] = k; self._set_keep.append(obj)          # (kept: no id is reused while pickling)
        return ("set", k) + tuple(r[1])

    def reducer_override(self, obj):
        if isinstance(obj, (set, frozenset)):                            # a set subclass, with its table's layout
            r = setlayout.reduce(obj)
            if r is None:
                self._by_value[id(obj)] = obj
            return NotImplemented if r is None else r
        if type(obj) is not types.FunctionType or ("<locals>" not in obj.__qualname__ and obj.__name__ != "<lambda>"):
            return NotImplemented
        cells = []
        for cell in obj.__closure__ or ():
            try:
                cells.append(cell.cell_contents)
            except ValueError:
                cells.append(_EmptyCell)
        return (_function_shell, (marshal.dumps(obj.__code__), obj.__module__, obj.__name__, len(cells)),
                (tuple(cells), obj.__defaults__, obj.__kwdefaults__, obj.__qualname__, dict(obj.__dict__)), None, None, _function_fill)


class _CheckpointUnpickler(pickle.Unpickler):
    """Reads a checkpoint: the sets `_CheckpointPickler` wrote as persistent ids come back with their tables."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._sets = {}

    def persistent_load(self, pid):
        if pid[0] == "set":
            obj = self._sets[pid[1]] = setlayout.rebuild(*pid[2:])
            return obj
        if pid[0] == "set_ref":
            return self._sets[pid[1]]
        raise pickle.UnpicklingError("unknown persistent id %r" % (pid[0],))


def _deep(fn):
    """Run fn() on a thread with a 512 MiB stack and a high recursion limit, the collector off: pickle recurses once per
    nesting level of the run's object graph."""
    box = {}

    def body():
        try:
            box["value"] = fn()
        except BaseException as e:                                     # re-raised in the caller
            box["error"] = e
    size, limit, collect = threading.stack_size(1 << 29), sys.getrecursionlimit(), gc.isenabled()
    sys.setrecursionlimit(1_000_000); gc.disable()
    try:
        t = threading.Thread(target=body); t.start(); t.join()
    finally:
        threading.stack_size(size); sys.setrecursionlimit(limit)
        if collect:
            gc.enable()
    if "error" in box:
        raise box["error"]
    return box.get("value")


def _checkpoint_header() -> dict:
    return dict(format=CHECKPOINT_FORMAT, interpreter=setlayout.INTERPRETER)


def _require_exact(what: str) -> None:
    """an exact checkpoint needs the set layouts; an interpreter without them is refused before
    anything is written or read, and nothing falls back to an ordinary pickle."""
    if not setlayout.OK:
        raise RuntimeError("cannot %s an exact checkpoint on %s: froq.setlayout's layout check failed" % (what, setlayout.INTERPRETER))


def save_checkpoint(path: str, state: dict) -> None:
    """Write the state atomically: a kill during the write leaves the previous checkpoint in place.  The file holds a
    header (the format and the interpreter), the state, and a trailer counting the sets recorded with their layouts and
    those pickled by value."""
    _require_exact("write")
    tmp = "%s.%d.tmp" % (path, os.getpid())

    def dump():
        with open(tmp, "wb") as f:
            pickle.dump(_checkpoint_header(), f, protocol=pickle.HIGHEST_PROTOCOL)
            p = _CheckpointPickler(f, protocol=pickle.HIGHEST_PROTOCOL)
            p.dump(state)
            pickle.dump(dict(sets_with_layout=len(p._set_keep), sets_by_value=len(p._by_value)), f, protocol=pickle.HIGHEST_PROTOCOL)
    _deep(dump)
    os.replace(tmp, path)


def checkpoint_header(path: str) -> dict:
    """The checkpoint's header, read and checked before its state is: the format and this interpreter."""
    with open(path, "rb") as f:
        try:
            hdr = pickle.load(f)
        except Exception as e:                                           # noqa: BLE001 (an older or foreign file)
            raise ValueError("%s is not a %s file (%s)" % (path, CHECKPOINT_FORMAT, type(e).__name__)) from e
    if not isinstance(hdr, dict) or hdr.get("format") != CHECKPOINT_FORMAT:
        raise ValueError("%s is not a %s file" % (path, CHECKPOINT_FORMAT))
    if hdr.get("interpreter") != setlayout.INTERPRETER:
        raise ValueError("checkpoint %s was written on %s; this is %s" % (path, hdr.get("interpreter"), setlayout.INTERPRETER))
    return hdr


def load_checkpoint(path: str) -> dict:
    _require_exact("read")
    checkpoint_header(path)

    def load():
        with open(path, "rb") as f:
            pickle.load(f)                                               # the header, checked above
            st = _CheckpointUnpickler(f).load()
            st["_set_counts"] = pickle.load(f)                           # the trailer
            return st
    return _deep(load)


def _rekey_table_caches(es, old_id: int, tables) -> None:
    """contract.py caches three maps on the event stream under id(sem.tables); the restored Tables object has a new id,
    so its entries move to it (they hold the stream's own restored atoms)."""
    for name in ("_certified_atoms", "_logical_events", "_atoms_by_wire"):
        cache = es.__dict__.get(name)
        if cache and old_id in cache:
            cache[id(tables)] = cache.pop(old_id)


_STOP = [False]                                                          # SIGUSR1: a split part stops at its next round


def _stop_requested(signum, frame):
    _STOP[0] = True


def _simulate_in_parts(simulator, fresh, checkpoint: str, request: dict, inputs: dict, every: float, stop_after, stop_after_rounds):
    """Upstream's `DecodingSimulator.run` loop for the arguments run_one passes (no cutoffs, no clock timeout, no
    progress bar): `initialize_experiment` (inside `fresh`), then `step_experiment` until `is_done` -- with the run state
    pickled to `checkpoint` every `every` seconds and when this part reaches `stop_after` seconds or `stop_after_rounds`
    rounds. An existing checkpoint is resumed instead, after checking that it was written for the same request and the
    same inputs (schedule, events, certificates, the per-file code hashes, snippet cache, latency table). Returns
    (simulator, policy, sem, lat, split record) when the run is done, None when the part stopped. SIGUSR1 stops the
    part at its next round as `stop_after` would (a lane hands its last units to 1-core
    lanes, which resume them)."""
    t_part = time.time()
    _STOP[0] = False
    if threading.current_thread() is threading.main_thread():            # (signals reach the main thread only)
        signal.signal(signal.SIGUSR1, _stop_requested)
    _require_exact("write")                                              # (before any work)
    if os.path.exists(checkpoint):
        st = load_checkpoint(checkpoint)
        if st.get("format") != CHECKPOINT_FORMAT:
            raise ValueError("%s is not a %s file" % (checkpoint, CHECKPOINT_FORMAT))
        if st["request"] != request:
            raise ValueError("checkpoint %s was written for %s, this call asks for %s: delete the checkpoint to start over"
                             % (checkpoint, {k: v for k, v in st["request"].items() if request.get(k) != v},
                                {k: v for k, v in request.items() if st["request"].get(k) != v}))
        diff = input_diff(st["inputs"], inputs)
        if diff:
            raise ValueError("checkpoint %s was written on inputs that are no longer current: %s (delete it to start over)" % (checkpoint, "; ".join(diff)))
        simulator, policy, sem, lat, split = st["simulator"], st["policy"], st["sem"], st["lat"], st["split"]
        split["save_seconds"] = round(split["save_seconds"] + max(0.0, os.path.getmtime(checkpoint) - st["saved_at"]), 1)   # the write that made this file
        LINK["decoder"] = simulator._decoding_manager                  # the module-level link the device and the policy read
        LINK["simulator"] = simulator                                  # ... and the progress stop's
        _rekey_table_caches(simulator._device_manager.es, st["tables_id"], sem.tables)
        split["parts"] += 1; split["resumed_at_rounds"].append(simulator._device_manager.current_round)
        split.setdefault("sets", []).append(st.get("_set_counts"))         # the sets each resumed part restored
        split["load_seconds"] = round(split["load_seconds"] + time.time() - t_part, 1)
        before = st["elapsed"]
    else:
        policy, sem, lat = fresh()
        split, before = dict(parts=1, resumed_at_rounds=[], saves=0, save_seconds=0.0, load_seconds=0.0), 0.0
    dev = simulator._device_manager
    first, last = dev.current_round, time.time()

    def save():
        t = time.time()
        split["saves"] += 1
        state = dict(format=CHECKPOINT_FORMAT, request=request, inputs=inputs, simulator=simulator, policy=policy, sem=sem, lat=lat,
                     tables_id=id(sem.tables), split=split, elapsed=before + t - t_part, round=dev.current_round, saved_at=t)
        save_checkpoint(checkpoint, state)
        split["save_seconds"] = round(split["save_seconds"] + time.time() - t, 1)   # counted here for the saves this part outlives
        print("checkpoint %s: round %d, %.1f s to write" % (checkpoint, dev.current_round, time.time() - t), flush=True)
    while not simulator.is_done():
        simulator.step_experiment(pending_window_count_cutoff=0, device_rounds_cutoff=0, print_interval=None)
        if simulator.is_done():
            break
        now = time.time()
        stop = (stop_after is not None and now - t_part >= stop_after) or \
               (stop_after_rounds is not None and dev.current_round - first >= stop_after_rounds) or _STOP[0]
        if stop or (every is not None and now - last >= every):
            save(); last = time.time()
            if stop:
                return None
    split["seconds"] = round(before + time.time() - t_part, 1)
    return simulator, policy, sem, lat, split


def run_arm(bench: str, distance: int, arm: str, seed: int, out_dir: str, **kw):
    """`run_one` for a registered arm (`froq.arms`): its base configuration, its options, its name.  An explicit keyword
    that contradicts one of the arm's options (a value other than run_one's default) is refused, never overridden."""
    base, opts = arms.resolve(arm)
    defaults = inspect.signature(run_one).parameters
    for k, v in opts.items():
        if k not in defaults:
            raise TypeError("arm %s sets %s, which run_one does not take" % (arm, k))
        if k in kw and kw[k] != defaults[k].default and kw[k] != v:
            raise ValueError("arm %s fixes %s = %r; the call asks for %r" % (arm, k, v, kw[k]))
    kw.update(opts)
    return run_one(bench, distance, base, seed, out_dir, arm_name=arm, **kw)


