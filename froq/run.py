def load_profile(prof_path: str, bench: str, distance: int, table: str, inputs: dict, decoders=None, client="modeled", f_flip=1.0,
                 spec_accuracy=0.9, strip_accuracy="lower", sens=None, strip_class_rule="legacy", strip_geometry_rule="legacy",
                 planner="client") -> dict:
    """Load and validate the training profile a Q run depends on (round-2 findings A4 / B3). It must record the
    TRAINING run of this problem -- seed 1, arm N, this (bench, d, table), K_train -- it must be complete (that run
    succeeded with every value verified and settled), and every input it was trained on (schedule, events, manifest and
    its fork commit, certificates, rules version, compile backend, latency table, predictor settings and the per-file
    hashes of the executing code) must equal the current ones. Anything else is refused, never guessed. part 1d:
    with the strip client, the strip class and geometry rules too (a profile that records none was trained under v7's
    rules, "legacy"); this check is on the profile's source, so E2E_AUDIT_PROFILE_CODE_EXEMPT, which only exempts code
    hashes, cannot bypass it."""
    with open(prof_path) as f:
        profile = json.load(f)
    src = profile.get("source") or {}
    want = dict(bench=bench, d=distance, table=table, arm="N", seed=TRAIN_SEED, K_train=K_TRAIN)
    off = {k: src.get(k) for k, v in want.items() if src.get(k) != v}
    if (src.get("decoders") or None) != (int(decoders) if decoders else None):   # trained under another decoder cap
        off["decoders"] = src.get("decoders")
    if src.get("client", "modeled") != client:                                   # trained with another prediction source
        off["client"] = src.get("client", "modeled")
    if client == "swiper" and float(src.get("f_flip", 1.0)) != float(f_flip):    # ... or another f_flip (its planning saw other values)
        off["f_flip"] = src.get("f_flip", 1.0)
    if float(src.get("speculation_accuracy", 0.9)) != float(spec_accuracy):     # ... or another SWIPER-SIM speculation accuracy
        off["speculation_accuracy"] = src.get("speculation_accuracy", 0.9)
    if client == "strip" and src.get("strip_accuracy", "lower") != strip_accuracy:   # ... or another strip accuracy mode
        off["strip_accuracy"] = src.get("strip_accuracy", "lower")
    for k, v in (("strip_class_rule", strip_class_rule), ("strip_geometry_rule", strip_geometry_rule)):
        if client == "strip" and src.get(k, "legacy") != v:                    # ... or other strip rules (absent: v7's)
            off[k] = src.get(k, "legacy")
    if (src.get("sensitivity") or {}) != (sens or {}):                          # or under other knobs
        off["sensitivity"] = src.get("sensitivity")
    want_pl = dict(client="swiper", f_flip=float(f_flip)) if planner == "swiper" and client != "swiper" else None
    if src.get("planner") != want_pl:                                           # ... or another planner routing (rule 41d)
        off["planner"] = src.get("planner")
    if off:
        raise ValueError("profile %s records %s; a Q run needs the profile written by the seed-%d N training run of %s"
                         % (prof_path, off, TRAIN_SEED, want))
    if profile.get("complete") is not True:
        raise ValueError("profile %s is incomplete: the training run did not finish with every value verified and settled "
                         "(re-run the seed-%d N configuration)" % (prof_path, TRAIN_SEED))
    rec_inputs, now_inputs = profile.get("inputs"), inputs
    exempt = audit_code_exempt()
    if exempt and isinstance(rec_inputs, dict):                       # part 1c, records-only audits: these files' hashes
        drop = lambda x: dict(x, code={f: h for f, h in (x.get("code") or {}).items() if f not in exempt})   # may differ
        rec_inputs, now_inputs = drop(rec_inputs), drop(inputs)
    diff = input_diff(rec_inputs, now_inputs)
    if diff:
        raise ValueError("profile %s was trained on inputs that are no longer current: %s (re-run the seed-%d N "
                         "configuration of this bench / d / table)" % (prof_path, "; ".join(diff), TRAIN_SEED))
    if (src.get("lss"), src.get("events")) != (inputs["lss"], inputs["events"]):
        raise ValueError("profile %s records source schedule / events %s but training inputs %s"
                         % (prof_path, (src.get("lss"), src.get("events")), (inputs["lss"], inputs["events"])))
    return profile


