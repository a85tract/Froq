def slow_half_wrong_set(ref_path: str, bench: str, distance: int, events: EventStream, seed: int, q_value: float,
                        budget=None) -> tuple:
    """The correlated-error client (gap analysis concern 1d): wrong predictions fall only on values in the
    slower half of resolution times, at the independent client's overall rate 1 - q.

    The resolution times come from the reference result `ref_path`: the N run of the same program, d and seed with the
    independent client (q 0.9, L 1), or (gap analysis rule 43b) the D-nci run of the same program, d, seed and
    budget B, which ignores the client, whatever client it ran with. Its `values` table gives each value's verdict
    latency (resolution = delivered - measured). Values ranked slowest first, ties by vid; the slower half is the first ceil(n / 2).
    A D-nci reference censored under rule 29 serves as well (rule 43b, amended 04:50): the values it never resolved rank
    slowest, ties by vid, and the record notes it (`error_ref_censored`, `error_ref_unresolved`). A slow value is wrong
    when its keyed prediction coin -- the independent client's own draw, key ("pred", producer event) -- falls below
    2 (1 - q); a fast value is never wrong. So the expected error rate stays 1 - q, the draw is paired with the
    independent client's (every value wrong there and slow is wrong here too), and the policy sees only the published
    value and c, as before. Returns (wrong producer events, the fingerprint record)."""
    ref = json.load(open(ref_path))
    who = (ref.get("arm"), ref.get("bench"), ref.get("d"), ref.get("seed"))
    dnci = who == ("D", bench, distance, seed) and ref.get("arm_name") == "Dnci"
    # rule 43b, amended 04:50: a D-nci reference censored under rule 29 serves too; the values it never resolved rank slowest
    censored = dnci and stopping_outcome(ref) == "censored" and not r29_check_problems(ref)
    if (who != ("N", bench, distance, seed) and not dnci) or (required_check_problems(ref) and not censored):
        raise ValueError("error reference %s must be a clean N run of %s d=%d seed %d, or its D-nci run at the same budget "
                         "(it records %s)" % (ref_path, bench, distance, seed, who + (ref.get("arm_name"),)))
    if dnci:                                                          # rule 43b: D-nci(B) of the run's own B
        B = (((ref.get("fingerprint") or {}).get("shared") or {}).get("budget") or {}).get("B")
        if budget is None or B != int(budget):
            raise ValueError("error reference %s is D-nci at budget %s; this run's is %s" % (ref_path, B, budget))
    elif (ref.get("predictor") or {}) != dict(q_value=0.9, client_latency=1):
        raise ValueError("error reference %s must use the independent client at q 0.9, L 1 (it records %s)" % (ref_path, ref.get("predictor")))
    vt = ref.get("values") or {}
    col = {f: i for i, f in enumerate(vt.get("fields", ()))}
    res = {row[col["vid"]]: row[col["resolution"]] for row in vt.get("rows", ())}
    specs = {sp.vid: sp.producer_event for sp in values_of(events)}
    if censored and not set(res) <= set(specs):
        raise ValueError("error reference %s: its value table names values this program does not have" % ref_path)
    if not censored and (set(res) != set(specs) or any(r is None for r in res.values())):
        raise ValueError("error reference %s: its value table does not cover this program's %d values with resolution times" % (ref_path, len(specs)))
    unresolved = [vid for vid in specs if res.get(vid) is None]       # (only a censored reference has any)
    ranked = sorted(specs, key=lambda vid: (res.get(vid) is not None, -(res.get(vid) or 0), vid))   # slowest first, ties by vid
    slow = ranked[:math.ceil(len(ranked) / 2)]
    krng = KeyedRNG(seed)
    wrong = sorted(vid for vid in slow if krng.uniform("pred", specs[vid]) < 2.0 * (1.0 - q_value))
    rec = dict(error_model="slow_half", error_ref=_sha(ref_path), error_wrong=len(wrong),
               error_wrong_sha=hashlib.sha256(json.dumps(wrong).encode()).hexdigest()[:16])
    if censored:
        rec.update(error_ref_censored=True, error_ref_unresolved=len(unresolved))
    return frozenset(specs[vid] for vid in wrong), rec


