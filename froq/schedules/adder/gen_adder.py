"""The n-bit Gidney temporary-AND adder (Gidney, "Halving the cost of quantum addition", arXiv:1709.06648, Figs. 3 and 4)
as Clifford+T OpenQASM that KEEPS its measurement-based uncomputation (review, concern 4).

Why this workload. The six Hamiltonian kernels come from pyLIQTR's temporary ANDs, and SWIPER's chain turns each
uncomputation into an unconditional CZ and drops its measurement (paper Sec. VIII). Here every temporary AND is
uncomputed as Gidney does it: an X-basis measurement of its target (`h`, then `measure` into a one-bit register) and a
CZ on the two controls classically controlled by the outcome (`if(m==1) cz`). The Froq fork of the lattice-surgery
compiler (w10: `measure` / `if(..==1) cz`, see SCOUTQ_FORK_W10.md) lowers the measurement to a destructive Z readout of
the patch and gives every instruction of the conditional CZ a scheduling dependency on it; the converter
(froq/semantics/compile.py) predicates the CZ on the measurement's result and conditions its .lss group on the
measurement's decode.

Gate conventions of the regenerated chain: T^dagger is written `t; s; z` (T S Z = T^dagger), as the corrected SWIPER
chain writes a -pi/4 rotation (gen_qasm_fixed), because the compiler lowers `tdg` exactly like `t` (C1
`Tdg_as_compiled`); every `cx` carries `// %AncillaNextToTarget` (gen_qasm.py: the slicer's placement default is not in
force for the first gate). No synthesis is needed: the program is Clifford+T as written, so SWIPER's cirq_to_ls (whose
only job is rotation synthesis and QASM output, and which drops measurements and classical control) is not used.

Wires (little-endian; b <- a + b mod 2^n, a unchanged, carries |0> in and out):
  a_i = q[i], b_i = q[n + i] (i = 0..n-1), c_i = q[2n + i - 1] (i = 1..n-1, register m<i> holds its uncomputation bit)
Carry recursion: c_{i+1} = c_i xor ((a_i xor c_i) and (b_i xor c_i)) = MAJ(a_i, b_i, c_i).

  python -m froq.schedules.adder.gen_adder N OUT.qasm (N >= 2)"""
from __future__ import annotations

import itertools
import sys


def wires(n: int) -> dict:
    return {"a": list(range(n)), "b": list(range(n, 2 * n)), "c": {i: 2 * n + i - 1 for i in range(1, n)}, "n_qubits": 3 * n - 1}


def adder_ops(n: int) -> list:
    """The adder as a list of ops: (gate, wires...) with gate in h, s, t, tdg, x, z, cx (control, target), measure (wire,
    register), cz_if (control, target, register)."""
    if n < 2:
        raise ValueError("the adder needs n >= 2 bits")
    W = wires(n)
    a, b, c = W["a"], W["b"], W["c"]
    ops = []

    def AND(x, y, t):                     # Fig. 3 (left): t <- x AND y, t in |0>; 4 T gates (one prepares |T> = T|+>)
        ops.extend([("h", t), ("t", t), ("cx", x, t), ("cx", y, t), ("cx", t, x), ("cx", t, y),
                    ("tdg", x), ("tdg", y), ("t", t), ("cx", t, x), ("cx", t, y), ("h", t), ("s", t)])

    def UNAND(x, y, t, reg):              # Fig. 3 (right): measure t in X; the phase (-1)^(x y m) is undone by CZ^m
        ops.extend([("h", t), ("measure", t, reg), ("cz_if", x, y, reg)])

    AND(a[0], b[0], c[1])
    for i in range(1, n - 1):
        ops.extend([("cx", c[i], a[i]), ("cx", c[i], b[i])])
        AND(a[i], b[i], c[i + 1])
        ops.append(("cx", c[i], c[i + 1]))
    ops.extend([("cx", c[n - 1], b[n - 1]), ("cx", a[n - 1], b[n - 1])])
    for i in range(n - 2, 0, -1):
        ops.append(("cx", c[i], c[i + 1]))
        UNAND(a[i], b[i], c[i + 1], "m%d" % (i + 1))
        ops.extend([("cx", c[i], a[i]), ("cx", a[i], b[i])])
    UNAND(a[0], b[0], c[1], "m1")
    ops.append(("cx", a[0], b[0]))
    return ops


def qasm_text(n: int) -> str:
    W = wires(n)
    lines = ["// Gidney temporary-AND adder, %d bits (arXiv:1709.06648 Figs. 3-4), generated by froq/schedules/adder/gen_adder.py" % n,
             "// wires: a_i = q[i], b_i = q[%d + i], carries c_i = q[%d + i - 1]; b <- a + b mod 2^%d; T^dagger written t; s; z" % (n, 2 * n, n),
             "", "OPENQASM 2.0;", 'include "qelib1.inc";', "", "qreg q[%d];" % W["n_qubits"]]
    lines += ["creg m%d[1];" % i for i in range(1, n)]
    lines.append("")
    for op in adder_ops(n):
        g = op[0]
        if g == "tdg":
            lines += ["t q[%d];" % op[1], "s q[%d];" % op[1], "z q[%d];" % op[1]]
        elif g == "cx":
            lines.append("cx q[%d],q[%d]; // %%AncillaNextToTarget" % (op[1], op[2]))
        elif g == "measure":
            lines.append("measure q[%d] -> %s[0];" % (op[1], op[2]))
        elif g == "cz_if":
            lines.append("if(%s==1) cz q[%d],q[%d];" % (op[3], op[1], op[2]))
        else:
            lines.append("%s q[%d];" % (g, op[1]))
    return "\n".join(lines) + "\n"


def counts(n: int) -> dict:
    ops = adder_ops(n)
    return {"qubits": wires(n)["n_qubits"], "t_gates": sum(o[0] in ("t", "tdg") for o in ops),
            "measurements": sum(o[0] == "measure" for o in ops), "conditional_cz": sum(o[0] == "cz_if" for o in ops),
            "cx": sum(o[0] == "cx" for o in ops)}


def reference_add(n: int, amplitudes: dict) -> dict:
    """The ideal adder on a superposition {(a, b): amplitude} -> {(a, (a + b) mod 2^n): amplitude}."""
    out = {}
    for (x, y), amp in amplitudes.items():
        key = (x, (x + y) % (1 << n))
        out[key] = out.get(key, 0) + amp
    return out


def all_inputs(n: int):
    return list(itertools.product(range(1 << n), repeat=2))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[-1].strip())
    n_bits, out = int(sys.argv[1]), sys.argv[2]
    with open(out, "w") as f:
        f.write(qasm_text(n_bits))
    print("DONE adder_%d %s" % (n_bits, counts(n_bits)))
